#include <iostream>
using namespace std;

int main()
{
    cout << "AND Operator : (5 & 3) = " << (5 & 3) << endl;
    cout << "OR Operator : (5 | 3) = " << (5 | 3) << endl;
    cout << "XOR Operator : (5 ^ 3) = " << (5 ^ 3) << endl;
    cout << " Operator : (5 ^ 3) = " << (5 ^ 3) << endl;
    return 0;
}